const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'quality_review_interactions.js'),'utf8');
const start=source.indexOf('function closedSelectionComparison(');
const end=source.indexOf('\nfunction normalizeFill(',start);
assert(start>=0&&end>start);
const compare=vm.runInNewContext('('+source.slice(start,end)+')');
const questions=Array.from({length:20},(_,i)=>({number:i+1,options:[['A','first'],['B','second'],['C','third']],answer:i%2?'B':'A'}));
const answers=Object.fromEntries(questions.map(q=>[q.number,q.answer]));
let result=compare(questions,answers);
assert.equal(result.total,20);assert.equal(result.matched,20);assert.equal(result.unanswered,0);
result=compare(questions,{...answers,1:'C',20:''});
assert.equal(result.matched,18);assert.equal(result.different,1);assert.equal(result.unanswered,1);
assert.equal(result.rows[0].state,'different');assert.equal(result.rows[19].state,'unanswered');
result=compare(questions);assert.equal(result.unanswered,20);assert.equal(result.different,0);
assert.equal(compare([{number:1,options:[],knownForms:['rest']}],{'1.1':'rest'}).available,false);
assert.equal(compare([{number:1,options:[['A','one'],['B','two']],knownForms:['one']}],{1:'A'}).available,false);
assert.equal(compare([{number:1,options:[['A','one'],['B','two']],answer:'C'}]).available,false);
assert.equal(compare([{number:1,options:[['A','one'],['A','two']],answer:'A'}]).available,false);
assert.equal(compare([questions[0],questions[0]],answers).available,false);
assert.equal(compare(questions,{1:'Z'}).available,false);
assert.equal(compare([]).available,false);
assert.equal(compare(undefined).available,false);
const shared=[{number:1,options:[['A','picture A'],['B','picture B']],answer:'A'},{number:2,options:[['A','picture A'],['B','picture B']],answer:'A'}];
assert.equal(compare(shared,{1:'A',2:'A'}).matched,2);
